/**
 * Renders a map spec to a top-down SVG diagram (M1-04).
 *
 *   pnpm map:svg                       # citadel.json -> docs/design/map-citadel.svg
 *   pnpm map:svg <in.json> <out.svg>
 *
 * Output is deterministic: same JSON in, byte-identical SVG out.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  MapSchema,
  polylineLength,
  type CampTier,
  type MapSpec,
  type Owner,
  type Region,
  type Structure,
  type Vec2,
} from '../../packages/content/src/index';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const inPath = process.argv[2] ?? join(root, 'packages/content/data/map/citadel.json');
const outPath = process.argv[3] ?? join(root, 'docs/design/map-citadel.svg');

// Art-direction palette (docs/design/art-direction.md §2.1).
const C = {
  wardenStone: '#CFC6B4',
  wardenMoss: '#6F9A4E',
  wardenBronze: '#B07A3C',
  wardenGold: '#E8B54A',
  hollowAsh: '#5E5A63',
  hollowIron: '#2E2B33',
  hollowEmber: '#8E5BD9',
  river: '#7FE3E0',
  danger: '#E5484D',
  ally: '#46A758',
  ink: '#1E1C22',
  paper: '#F4F1EA',
};

const MAP_PX = 1000;
const PAD = 24;
const LEGEND_W = 300;

const parsed = MapSchema.safeParse(JSON.parse(readFileSync(inPath, 'utf8')));
if (!parsed.success) {
  console.error(parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('\n'));
  process.exit(1);
}
const map: MapSpec = parsed.data;

const scale = MAP_PX / Math.max(map.size.width, map.size.depth);
const n = (v: number): string => {
  const r = Math.round(v * 10) / 10;
  return Object.is(r, -0) ? '0' : String(r);
};
const sx = (p: Vec2): number => PAD + (p.x + map.size.width / 2) * scale;
const sy = (p: Vec2): number => PAD + (map.size.depth / 2 - p.z) * scale;
const pt = (p: Vec2): string => `${n(sx(p))},${n(sy(p))}`;
const pts = (ps: readonly Vec2[]): string => ps.map(pt).join(' ');
const esc = (s: string): string =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const factionColor = (f: Owner): string =>
  f === 'wardens' ? C.wardenGold : f === 'hollow' ? C.hollowEmber : C.paper;

function regionStyle(r: Region): string {
  const side = r.faction;
  switch (r.tag) {
    case 'base':
      return side === 'wardens'
        ? `fill="${C.wardenStone}" stroke="${C.wardenBronze}" stroke-width="2"`
        : `fill="${C.hollowIron}" stroke="${C.hollowEmber}" stroke-width="2"`;
    case 'highground':
      return side === 'wardens'
        ? `fill="${C.wardenStone}" fill-opacity="0.85" stroke="${C.wardenBronze}" stroke-width="1.5" stroke-dasharray="4 2"`
        : `fill="${C.hollowAsh}" stroke="${C.hollowEmber}" stroke-width="1.5" stroke-dasharray="4 2"`;
    case 'jungle':
      return side === 'wardens'
        ? `fill="${C.wardenMoss}" fill-opacity="0.55"`
        : `fill="${C.hollowIron}" fill-opacity="0.55"`;
    case 'river':
      return `fill="${C.river}"`;
    case 'pit':
      return `fill="${C.hollowIron}" fill-opacity="0.85"`;
    case 'lane':
      return `fill="${C.wardenStone}" fill-opacity="0.55"`;
    case 'unwalkable':
      return `fill="${C.hollowIron}" fill-opacity="0.92"`;
  }
}

const tagOrder: Region['tag'][] = [
  'jungle',
  'lane',
  'river',
  'highground',
  'base',
  'pit',
  'unwalkable',
];

const out: string[] = [];
const W = PAD * 2 + MAP_PX + LEGEND_W;
const H = PAD * 2 + MAP_PX;
out.push(
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" font-family="system-ui, -apple-system, 'Segoe UI', sans-serif">`,
  `<title>${esc(map.name)}: top-down map diagram (generated by tools/map/render-svg.ts)</title>`,
  '<defs>',
  `<pattern id="trees" width="10" height="10" patternUnits="userSpaceOnUse"><circle cx="3" cy="3" r="2" fill="${C.ink}" fill-opacity="0.45"/><circle cx="8" cy="8" r="1.6" fill="${C.ink}" fill-opacity="0.35"/></pattern>`,
  `<pattern id="hatch" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><line x1="0" y1="0" x2="0" y2="6" stroke="${C.hollowAsh}" stroke-width="2"/></pattern>`,
  '</defs>',
  `<rect width="${W}" height="${H}" fill="${C.paper}"/>`,
);

// Low ground: the river splits the square into a Warden half (south) and a Hollow half (north).
const hw = map.size.width / 2;
const hd = map.size.depth / 2;
const riverLine = map.river.waypoints;
out.push('<g id="ground">');
out.push(
  `<polygon points="${pts([...riverLine, { x: hw, z: -hd }, { x: -hw, z: -hd }])}" fill="${C.wardenMoss}" fill-opacity="0.3"/>`,
  `<polygon points="${pts([...riverLine, { x: hw, z: hd }, { x: -hw, z: hd }])}" fill="${C.hollowAsh}" fill-opacity="0.45"/>`,
);
out.push('</g>');

out.push('<g id="regions">');
for (const tag of tagOrder) {
  for (const r of map.regions.filter((x) => x.tag === tag)) {
    out.push(`<polygon id="${r.id}" points="${pts(r.polygon)}" ${regionStyle(r)}/>`);
    if (tag === 'unwalkable' && !r.id.startsWith('border')) {
      out.push(`<polygon points="${pts(r.polygon)}" fill="url(#hatch)"/>`);
    }
  }
  if (tag === 'jungle') {
    out.push('<g id="trees">');
    for (const t of map.treeZones) {
      out.push(
        `<polygon id="${t.id}" points="${pts(t.polygon)}" fill="url(#trees)" fill-opacity="${n(0.4 + t.density * 0.6)}"/>`,
      );
    }
    out.push('</g>');
  }
}
out.push('</g>');

// River centreline and lanes.
out.push(
  `<polyline points="${pts(riverLine)}" fill="none" stroke="#FFFFFF" stroke-opacity="0.7" stroke-width="1.5" stroke-dasharray="6 6"/>`,
);
out.push('<g id="lanes">');
for (const lane of map.lanes) {
  out.push(
    `<polyline points="${pts(lane.waypoints)}" fill="none" stroke="${C.wardenBronze}" stroke-width="2.5" stroke-linejoin="round" stroke-linecap="round"/>`,
  );
  const mid = lane.waypoints[Math.floor(lane.waypoints.length / 2)]!;
  const lx = sx(mid) + (lane.id === 'top' ? 0 : lane.id === 'bottom' ? 0 : 14);
  const ly = sy(mid) + (lane.id === 'top' ? -10 : lane.id === 'bottom' ? 18 : -6);
  out.push(
    `<text x="${n(lx)}" y="${n(ly)}" font-size="12" font-weight="700" fill="${C.ink}" text-anchor="middle">${lane.id.toUpperCase()} · ${Math.round(polylineLength(lane.waypoints))}u</text>`,
  );
}
out.push('</g>');

// Ramps: chevron pointing uphill (from -> to).
function chevron(p: Vec2, dirDeg: number, len: number, width: number, color: string): string {
  const a = (-dirDeg * Math.PI) / 180; // screen y is flipped
  const fx = Math.cos(a);
  const fy = Math.sin(a);
  const cx = sx(p);
  const cy = sy(p);
  // Glyph size is capped so wide base ramps don't hide the towers around them.
  const L = Math.min(14, Math.max(9, len * scale));
  const Wd = Math.min(16, Math.max(9, width * scale * 0.5));
  const tip = [cx + fx * (L / 2), cy + fy * (L / 2)];
  const b1 = [cx - fx * (L / 2) - fy * (Wd / 2), cy - fy * (L / 2) + fx * (Wd / 2)];
  const b2 = [cx - fx * (L / 2) + fy * (Wd / 2), cy - fy * (L / 2) - fx * (Wd / 2)];
  return `<polygon points="${[b1, tip, b2].map(([x, y]) => `${n(x!)},${n(y!)}`).join(' ')}" fill="${color}" stroke="${C.ink}" stroke-width="1"/>`;
}
out.push('<g id="ramps">');
for (const r of map.ramps) out.push(chevron(r.position, r.direction, r.length, r.width, C.paper));
out.push('</g>');

// Boss pit.
const pit = map.bossPit;
const pr = pit.radius * scale;
const ea = (-pit.entranceFacing * Math.PI) / 180;
out.push(
  '<g id="boss-pit">',
  `<circle cx="${n(sx(pit.position))}" cy="${n(sy(pit.position))}" r="${n(pr)}" fill="none" stroke="${C.danger}" stroke-width="3" stroke-dasharray="${n(pr * 5.2)} ${n(pr * 1.08)}" transform="rotate(${n((ea * 180) / Math.PI + 31)} ${n(sx(pit.position))} ${n(sy(pit.position))})"/>`,
  `<text x="${n(sx(pit.position))}" y="${n(sy(pit.position) + 4)}" font-size="10" font-weight="700" fill="${C.danger}" text-anchor="middle">BOSS</text>`,
  '</g>',
);

// Rune spots.
out.push('<g id="runes">');
for (const r of map.runeSpots) {
  const x = sx(r.position);
  const y = sy(r.position);
  out.push(
    `<polygon points="${n(x)},${n(y - 9)} ${n(x + 7)},${n(y)} ${n(x)},${n(y + 9)} ${n(x - 7)},${n(y)}" fill="#FFFFFF" stroke="${C.ink}" stroke-width="1.5"/>`,
    `<text x="${n(x)}" y="${n(y + 3.5)}" font-size="9" font-weight="700" fill="${C.ink}" text-anchor="middle">R</text>`,
  );
}
out.push('</g>');

// Camps.
const campStyle: Record<CampTier, { r: number; color: string; label: string }> = {
  small: { r: 6, color: C.ally, label: 'S' },
  medium: { r: 7.5, color: C.wardenBronze, label: 'M' },
  large: { r: 9, color: C.danger, label: 'L' },
  ancient: { r: 10.5, color: C.ink, label: 'A' },
};
out.push('<g id="camps">');
for (const c of map.camps) {
  const s = campStyle[c.tier];
  const x = sx(c.position);
  const y = sy(c.position);
  out.push(
    `<circle cx="${n(x)}" cy="${n(y)}" r="${n(c.spawnBoxRadius * scale)}" fill="none" stroke="${s.color}" stroke-opacity="0.6" stroke-dasharray="2 2"/>`,
    `<circle cx="${n(x)}" cy="${n(y)}" r="${s.r}" fill="${s.color}" stroke="#FFFFFF" stroke-width="1.5"/>`,
    `<text x="${n(x)}" y="${n(y + 3.5)}" font-size="9" font-weight="700" fill="#FFFFFF" text-anchor="middle">${s.label}</text>`,
  );
}
out.push('</g>');

// Structures.
function structureGlyph(s: Structure): string {
  const x = sx(s.position);
  const y = sy(s.position);
  const fill = factionColor(s.faction);
  const stroke = C.ink;
  const text = (label: string, size = 9, color = C.ink): string =>
    `<text x="${n(x)}" y="${n(y + size * 0.36)}" font-size="${size}" font-weight="700" fill="${color}" text-anchor="middle">${label}</text>`;
  const textColor = s.faction === 'hollow' ? '#FFFFFF' : C.ink;
  switch (s.type) {
    case 'tower':
      return (
        `<rect x="${n(x - 7)}" y="${n(y - 7)}" width="14" height="14" fill="${fill}" stroke="${stroke}" stroke-width="1.5"/>` +
        text(String(s.tier), 10, textColor)
      );
    case 'barracks_melee':
    case 'barracks_ranged':
      return (
        `<rect x="${n(x - 8)}" y="${n(y - 5.5)}" width="16" height="11" rx="2" fill="${fill}" stroke="${stroke}" stroke-width="1.2"/>` +
        text(s.type === 'barracks_melee' ? 'M' : 'R', 8, textColor)
      );
    case 'ancient':
      return (
        `<polygon points="${n(x)},${n(y - 16)} ${n(x + 16)},${n(y)} ${n(x)},${n(y + 16)} ${n(x - 16)},${n(y)}" fill="${fill}" stroke="${stroke}" stroke-width="2"/>` +
        text('★', 14, textColor)
      );
    case 'fountain':
      return (
        `<circle cx="${n(x)}" cy="${n(y)}" r="11" fill="${C.river}" stroke="${fill}" stroke-width="3"/>` +
        text('F', 10)
      );
    case 'shop_base':
    case 'shop_side':
    case 'shop_secret': {
      const label = s.type === 'shop_base' ? '$' : s.type === 'shop_side' ? 'S$' : '?$';
      return (
        `<rect x="${n(x - 10)}" y="${n(y - 7)}" width="20" height="14" rx="7" fill="${s.faction === 'neutral' ? '#FFFFFF' : fill}" stroke="${C.wardenBronze}" stroke-width="2"/>` +
        text(label, 8, s.faction === 'hollow' ? '#FFFFFF' : C.ink)
      );
    }
  }
}
out.push('<g id="structures">');
for (const s of map.structures) out.push(`<g id="${s.id}">${structureGlyph(s)}</g>`);
out.push('</g>');

// Faction labels, in the margin next to each home corner so they never cover map features.
out.push(
  `<text x="${PAD}" y="${PAD + MAP_PX + 17}" font-size="13" font-weight="800" fill="${C.wardenBronze}">WARDENS · Hearthstone (south-west)</text>`,
  `<text x="${PAD + MAP_PX}" y="${PAD - 7}" font-size="13" font-weight="800" fill="${C.hollowEmber}" text-anchor="end">HOLLOW · Hollow Crown (north-east)</text>`,
);

// Map frame.
out.push(
  `<rect x="${PAD}" y="${PAD}" width="${n(map.size.width * scale)}" height="${n(map.size.depth * scale)}" fill="none" stroke="${C.ink}" stroke-width="2"/>`,
);

// Legend.
const lx = PAD * 2 + MAP_PX;
let ly = PAD + 8;
const L: string[] = [];
const heading = (t: string): void => {
  ly += 10;
  L.push(
    `<text x="${lx}" y="${ly}" font-size="12" font-weight="800" fill="${C.ink}">${esc(t)}</text>`,
  );
  ly += 18;
};
const swatch = (attrs: string, t: string): void => {
  L.push(`<rect x="${lx}" y="${ly - 11}" width="22" height="14" ${attrs}/>`);
  L.push(`<text x="${lx + 30}" y="${ly}" font-size="11" fill="${C.ink}">${esc(t)}</text>`);
  ly += 20;
};
const glyphRow = (glyph: string, t: string): void => {
  L.push(glyph);
  L.push(`<text x="${lx + 30}" y="${ly}" font-size="11" fill="${C.ink}">${esc(t)}</text>`);
  ly += 22;
};
L.push(
  `<text x="${lx}" y="${ly + 10}" font-size="20" font-weight="800" fill="${C.ink}">${esc(map.name)}</text>`,
);
ly += 30;
const towers = map.structures.filter((s) => s.type === 'tower').length / 2;
const barracks = map.structures.filter((s) => s.type.startsWith('barracks')).length / 2;
L.push(
  `<text x="${lx}" y="${ly}" font-size="11" fill="${C.hollowAsh}">${map.size.width}×${map.size.depth} units · +x east, +z north</text>`,
);
ly += 16;
L.push(
  `<text x="${lx}" y="${ly}" font-size="11" fill="${C.hollowAsh}">Per side: ${towers} towers, ${barracks} barracks, ${map.camps.length / 2} camps</text>`,
);
ly += 8;

heading('Terrain');
const hl = map.heightLevels;
swatch(
  `fill="${C.wardenStone}" stroke="${C.wardenBronze}" stroke-width="2"`,
  `Warden base (high, ${hl.high})`,
);
swatch(
  `fill="${C.hollowIron}" stroke="${C.hollowEmber}" stroke-width="2"`,
  `Hollow base (high, ${hl.high})`,
);
swatch(
  `fill="${C.wardenStone}" stroke="${C.wardenBronze}" stroke-dasharray="4 2"`,
  `Overlook plateau (mid, ${hl.mid})`,
);
swatch(`fill="${C.wardenMoss}" fill-opacity="0.55"`, `Warden jungle (low, ${hl.low})`);
swatch(`fill="${C.hollowIron}" fill-opacity="0.55"`, `Hollow jungle (low, ${hl.low})`);
swatch(`fill="${C.wardenStone}" fill-opacity="0.55"`, 'Lane corridor (low)');
swatch(`fill="${C.river}"`, `River of light (river, ${hl.river})`);
swatch(
  `fill="url(#trees)" stroke="${C.hollowAsh}" stroke-width="0.5"`,
  'Tree zone (dots = density)',
);
swatch(`fill="${C.hollowIron}"`, 'Unwalkable (border, rocks)');

heading('Structures');
const g = (x: number, y: number, body: string): string =>
  `<g transform="translate(${x} ${y})">${body}</g>`;
const gy = (): number => ly - 4;
glyphRow(
  g(
    lx + 11,
    gy(),
    `<rect x="-7" y="-7" width="14" height="14" fill="${C.wardenGold}" stroke="${C.ink}" stroke-width="1.5"/><text y="3.6" font-size="10" font-weight="700" text-anchor="middle">2</text>`,
  ),
  'Tower, labelled with tier (1–4)',
);
glyphRow(
  g(
    lx + 11,
    gy(),
    `<rect x="-8" y="-5.5" width="16" height="11" rx="2" fill="${C.hollowEmber}" stroke="${C.ink}" stroke-width="1.2"/><text y="2.9" font-size="8" font-weight="700" fill="#FFF" text-anchor="middle">M</text>`,
  ),
  'Barracks: M melee, R ranged',
);
glyphRow(
  g(
    lx + 11,
    gy(),
    `<polygon points="0,-10 10,0 0,10 -10,0" fill="${C.wardenGold}" stroke="${C.ink}" stroke-width="2"/>`,
  ),
  'Ancient (Hearthstone / Hollow Crown)',
);
glyphRow(
  g(lx + 11, gy(), `<circle r="9" fill="${C.river}" stroke="${C.wardenGold}" stroke-width="3"/>`),
  'Fountain (spawn)',
);
glyphRow(
  g(
    lx + 11,
    gy(),
    `<rect x="-10" y="-7" width="20" height="14" rx="7" fill="#FFF" stroke="${C.wardenBronze}" stroke-width="2"/><text y="2.9" font-size="8" font-weight="700" text-anchor="middle">?$</text>`,
  ),
  'Shops: $ base, S$ side, ?$ secret',
);
swatch(`fill="${C.wardenGold}"`, 'Wardens (gold)');
swatch(`fill="${C.hollowEmber}"`, 'Hollow (violet)');

heading('Neutrals');
for (const tier of ['small', 'medium', 'large', 'ancient'] as const) {
  const s = campStyle[tier];
  glyphRow(
    g(
      lx + 11,
      gy(),
      `<circle r="${s.r}" fill="${s.color}" stroke="#FFF" stroke-width="1.5"/><text y="3.2" font-size="9" font-weight="700" fill="#FFF" text-anchor="middle">${s.label}</text>`,
    ),
    `${tier[0]!.toUpperCase()}${tier.slice(1)} camp (dashed = spawn box)`,
  );
}
glyphRow(
  g(
    lx + 11,
    gy(),
    `<polygon points="0,-9 7,0 0,9 -7,0" fill="#FFF" stroke="${C.ink}" stroke-width="1.5"/><text y="3.2" font-size="9" font-weight="700" text-anchor="middle">R</text>`,
  ),
  'Rune spot',
);
glyphRow(
  g(lx + 11, gy(), `<circle r="9" fill="none" stroke="${C.danger}" stroke-width="3"/>`),
  'Boss pit (gap = entrance)',
);
glyphRow(
  g(lx + 11, gy(), `<polygon points="-6,6 0,-7 6,6" fill="${C.paper}" stroke="${C.ink}"/>`),
  'Ramp, arrow points uphill',
);
glyphRow(
  g(
    lx + 11,
    gy(),
    `<line x1="-11" y1="0" x2="11" y2="0" stroke="${C.wardenBronze}" stroke-width="2.5"/>`,
  ),
  'Lane path (length in world units)',
);
out.push('<g id="legend">', ...L, '</g>');
out.push('</svg>');

writeFileSync(outPath, out.join('\n') + '\n');
console.log(`wrote ${relative(root, outPath)}`);

/**
 * Generate CREDITS.md from the pack manifests.
 *   pnpm assets:credits          # write CREDITS.md
 *   pnpm assets:credits --check  # CI: fail if CREDITS.md is stale or a pack is invalid
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadManifests, ROOT } from './manifest';

const rows = loadManifests().map(
  (m) =>
    `| [${m.name}](${m.source}) | ${m.author} | [${m.license}](${m.licenseUrl}) | ${m.usedFor} |`,
);

const content = `# Credits

All third-party art in Rise of Citadel is released under CC0 (public domain). Credit is not required, but we give it anyway. Thank you to these creators.

Generated by \`pnpm assets:credits\` from \`assets-src/*/manifest.json\`. Do not edit by hand.

| Pack | Author | License | Used for |
|---|---|---|---|
${rows.join('\n')}
`;

const file = join(ROOT, 'CREDITS.md');
if (process.argv.includes('--check')) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== content) {
    console.error('CREDITS.md is out of date. Run `pnpm assets:credits`.');
    process.exit(1);
  }
  console.log(`CREDITS.md up to date (${rows.length} pack(s))`);
} else {
  writeFileSync(file, content);
  console.log(`wrote CREDITS.md (${rows.length} pack(s))`);
}
